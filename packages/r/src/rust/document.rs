fn main() -> std::io::Result<()> {
    let wrappers = shrinkage_r::get_shrinkage_metadata().make_r_wrappers(true, "shrinkage")?;
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../R/extendr-wrappers.R");
    std::fs::write(
        path,
        format!("# Generated by extendr.\n\n{}\n", wrappers.trim_end()),
    )
}
